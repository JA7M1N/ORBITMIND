"""
OrbitalMind — SQLAlchemy 2.0 ORM Models
=========================================
Declarative models for all four OrbitalMind tables:

    DisasterEvent    ──┬── AffectedZone
                       └── PriorityResult ── AdminZone

Geometry columns
----------------
GeoAlchemy2 ``Geometry`` is used when PostGIS is installed.
If ``geoalchemy2`` is not importable (or PostGIS is unavailable), we fall
back to ``Text`` columns that store GeoJSON strings.  A ``_POSTGIS_AVAILABLE``
flag is exposed so application code can branch when needed.

Usage
-----
::

    from backend.db.models import DisasterEvent, PriorityResult
    from backend.db.connection import get_db

    async with AsyncSessionLocal() as db:
        result = await db.execute(
            select(DisasterEvent).where(DisasterEvent.disaster_type == "flood")
        )
        events = result.scalars().all()
"""
from __future__ import annotations

import uuid
from datetime import date, datetime
from typing import Any, List, Optional

from sqlalchemy import (
    BigInteger,
    Date,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import (
    DeclarativeBase,
    Mapped,
    mapped_column,
    relationship,
)

# ── GeoAlchemy2 / PostGIS ─────────────────────────────────────────────────────

try:
    from geoalchemy2 import Geometry as _Geometry  # type: ignore[import]

    _POSTGIS_AVAILABLE = True

    def _geom(geom_type: str = "GEOMETRY", srid: int = 4326) -> Any:
        """Return a GeoAlchemy2 Geometry column type."""
        return _Geometry(geom_type, srid=srid)

except ImportError:
    _POSTGIS_AVAILABLE = False

    def _geom(geom_type: str = "GEOMETRY", srid: int = 4326) -> Any:  # type: ignore[misc]
        """Fallback: store geometry as GeoJSON text."""
        return Text()


# ── Declarative Base ──────────────────────────────────────────────────────────


class Base(DeclarativeBase):
    """Shared declarative base — all models inherit from this."""
    pass


# ── Model: DisasterEvent ──────────────────────────────────────────────────────


class DisasterEvent(Base):
    """One discrete disaster event from any of the 5 satellite modules.

    Each event maps to a disaster_type (flood / wildfire / landslide /
    cyclone / earthquake) and carries a geographic bounding box.

    Relationships
    -------------
    affected_zones   : AffectedZone  — satellite-detected polygons
    priority_results : PriorityResult — scored admin districts
    """

    __tablename__ = "disaster_events"

    event_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment="Primary key — generated by PostgreSQL gen_random_uuid()",
    )
    disaster_type: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        index=True,
        comment="One of: flood | wildfire | landslide | cyclone | earthquake",
    )
    display_name: Mapped[str] = mapped_column(String(200), nullable=False)
    region: Mapped[Optional[str]] = mapped_column(String(200))
    state: Mapped[Optional[str]] = mapped_column(String(100))
    date_start: Mapped[Optional[date]] = mapped_column(Date)
    date_end: Mapped[Optional[date]] = mapped_column(Date)
    status: Mapped[str] = mapped_column(
        String(20), server_default="live",
        comment="live | demo | archived"
    )
    data_source: Mapped[Optional[str]] = mapped_column(
        String(200),
        comment="e.g. 'Sentinel-1 SAR + Attention U-Net'",
    )
    thumbnail_color: Mapped[Optional[str]] = mapped_column(
        String(10), comment="Hex colour for UI cards (#1e40af)"
    )
    description: Mapped[Optional[str]] = mapped_column(Text)

    # Geometry bounding box (PostGIS POLYGON, SRID 4326)
    bbox: Mapped[Optional[Any]] = mapped_column(
        _geom("POLYGON", 4326),
        comment="Bounding polygon in WGS-84 (PostGIS GEOMETRY)",
    )
    # Text fallback when PostGIS not installed
    bbox_text: Mapped[Optional[str]] = mapped_column(
        Text, comment="WKT bbox string (fallback without PostGIS)"
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    # ── Relationships ──────────────────────────────────────────────────────
    affected_zones: Mapped[List["AffectedZone"]] = relationship(
        "AffectedZone",
        back_populates="event",
        cascade="all, delete-orphan",
        lazy="select",
    )
    priority_results: Mapped[List["PriorityResult"]] = relationship(
        "PriorityResult",
        back_populates="event",
        cascade="all, delete-orphan",
        lazy="select",
    )

    def __repr__(self) -> str:
        return (
            f"DisasterEvent(event_id={str(self.event_id)[:8]}…, "
            f"disaster_type={self.disaster_type!r}, "
            f"display_name={self.display_name!r})"
        )


# ── Model: AffectedZone ───────────────────────────────────────────────────────


class AffectedZone(Base):
    """A single satellite-detected affected polygon.

    geometry is stored as a PostGIS Geometry (Polygon / MultiPolygon) in
    SRID 4326.  The ``confidence`` field carries the U-Net / detection
    algorithm confidence score in [0, 1].

    ``intensity_metadata`` is a JSONB dict holding disaster-specific fields:
    - flood:     SAR backscatter delta, water depth proxy
    - wildfire:  NBR value, burn severity class
    - landslide: slope angle, displacement vector
    - cyclone:   wind-speed band, storm track distance
    - earthquake: PGA value, ShakeMap intensity
    """

    __tablename__ = "affected_zones"

    zone_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    event_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("disaster_events.event_id", ondelete="CASCADE"),
        index=True,
    )
    disaster_type: Mapped[Optional[str]] = mapped_column(String(30))

    # PostGIS geometry (active when PostGIS installed)
    geom: Mapped[Optional[Any]] = mapped_column(
        _geom("GEOMETRY", 4326),
        comment="Polygon / MultiPolygon in WGS-84 (PostGIS)",
    )
    # GeoJSON text fallback (always populated)
    geom_text: Mapped[Optional[str]] = mapped_column(
        Text, comment="GeoJSON geometry string (text fallback)"
    )
    confidence: Mapped[Optional[float]] = mapped_column(
        Float, comment="Detection confidence [0, 1]"
    )
    area_km2: Mapped[Optional[float]] = mapped_column(Float)
    intensity_metadata: Mapped[Optional[dict]] = mapped_column(
        JSONB,
        server_default="{}",
        comment="Disaster-specific intensity fields (see class docstring)",
    )
    source: Mapped[str] = mapped_column(
        String(50), server_default="demo",
        comment="unet_inference | demo | gee_export"
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    # ── Relationship ───────────────────────────────────────────────────────
    event: Mapped[Optional["DisasterEvent"]] = relationship(
        "DisasterEvent", back_populates="affected_zones"
    )

    def __repr__(self) -> str:
        return (
            f"AffectedZone(zone_id={str(self.zone_id)[:8]}…, "
            f"disaster_type={self.disaster_type!r}, "
            f"confidence={self.confidence})"
        )


# ── Model: AdminZone ──────────────────────────────────────────────────────────


class AdminZone(Base):
    """An administrative district used as the scoring unit.

    Pre-populated from Census 2011 data.  Geometry holds district boundaries
    in WGS-84 (MultiPolygon).  The ``population`` field is the 2011 census
    figure — used in the priority scoring population_score component.
    """

    __tablename__ = "admin_zones"

    zone_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    name: Mapped[Optional[str]] = mapped_column(String(200), index=True)
    district: Mapped[Optional[str]] = mapped_column(String(200))
    state: Mapped[Optional[str]] = mapped_column(String(100), index=True)
    population: Mapped[Optional[int]] = mapped_column(
        BigInteger, comment="Census 2011 district population"
    )
    area_km2: Mapped[Optional[float]] = mapped_column(Float)

    # PostGIS geometry (district boundary)
    geom: Mapped[Optional[Any]] = mapped_column(
        _geom("MULTIPOLYGON", 4326),
        comment="District boundary MultiPolygon in WGS-84",
    )
    geom_text: Mapped[Optional[str]] = mapped_column(Text)

    # ── Relationship ───────────────────────────────────────────────────────
    priority_results: Mapped[List["PriorityResult"]] = relationship(
        "PriorityResult",
        back_populates="admin_zone",
        lazy="select",
    )

    def __repr__(self) -> str:
        return (
            f"AdminZone(name={self.name!r}, state={self.state!r}, "
            f"population={self.population})"
        )


# ── Model: PriorityResult ─────────────────────────────────────────────────────


class PriorityResult(Base):
    """Scored output for one (event, admin_zone) pair.

    Created by ``calculate_priority_score()`` or inserted from pre-computed
    demo data.  ``priority_rank = 1`` is the HIGHEST priority zone.

    Score formula
    -------------
    score = w_pop × population_score
          + w_inf × infra_score
          + w_acc × (1 - roads_disrupted_pct)   ← access_score
          + w_int × intensity_score

    where weights come from ``scoring_weights`` (JSONB snapshot).

    ``scoring_weights`` contains::

        {
            "population": 0.40,
            "infra":      0.30,
            "access":     0.20,
            "intensity":  0.10
        }

    Keys vary by disaster type — see ``docs/scoring_weights.md``.
    """

    __tablename__ = "priority_results"

    result_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    event_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("disaster_events.event_id", ondelete="CASCADE"),
        index=True,
    )
    admin_zone_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("admin_zones.zone_id"),
        index=True,
    )
    disaster_type: Mapped[Optional[str]] = mapped_column(String(30))
    zone_name: Mapped[Optional[str]] = mapped_column(String(200))
    priority_rank: Mapped[Optional[int]] = mapped_column(
        Integer, comment="1 = highest priority district"
    )
    priority_score: Mapped[Optional[float]] = mapped_column(
        Float, comment="Composite score in [0, 1]"
    )

    # Component scores (for transparency)
    population_score: Mapped[Optional[float]] = mapped_column(Float)
    infra_score: Mapped[Optional[float]] = mapped_column(Float)
    access_score: Mapped[Optional[float]] = mapped_column(Float)
    intensity_score: Mapped[Optional[float]] = mapped_column(Float)

    # Infrastructure impact counts (from OSM spatial overlay)
    hospitals_affected: Mapped[int] = mapped_column(Integer, server_default="0")
    schools_affected: Mapped[int] = mapped_column(Integer, server_default="0")
    bridges_affected: Mapped[int] = mapped_column(Integer, server_default="0")

    # Weight snapshot for auditability
    scoring_weights: Mapped[Optional[dict]] = mapped_column(
        JSONB,
        comment="Weights snapshot: {population, infra, access, intensity}",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    # ── Relationships ──────────────────────────────────────────────────────
    event: Mapped[Optional["DisasterEvent"]] = relationship(
        "DisasterEvent", back_populates="priority_results"
    )
    admin_zone: Mapped[Optional["AdminZone"]] = relationship(
        "AdminZone", back_populates="priority_results"
    )

    def __repr__(self) -> str:
        return (
            f"PriorityResult(zone_name={self.zone_name!r}, "
            f"rank={self.priority_rank}, "
            f"score={self.priority_score})"
        )
